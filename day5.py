# •        Object code
#          An object code is the low-level binary representation of your program generated automatically when the compiler processes your code.
#          It is formatted into raw binary instruction blocks of 0s and 1s.

# •        Executable file
#          An excecutable file is the finalized software package ready for immediate computer excecution.
